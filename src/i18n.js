export function localeFor(language) {
  return language === 'en' ? 'en-US' : 'pt-BR'
}

// Textos centralizados; parâmetros mantêm números e dados fora das traduções.
export function translator(language) {
  return (message, values = {}) => {
    const text = language === 'en' ? (english[message] ?? message) : message
    return text.replace(/\{(\w+)\}/g, (match, key) => values[key] ?? match)
  }
}

export function initialLanguage() {
  try { return localStorage.getItem('currency-language') === 'en' ? 'en' : 'pt' }
  catch { return 'pt' }
}
